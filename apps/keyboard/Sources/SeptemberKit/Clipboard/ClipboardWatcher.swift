import Foundation

/// The general clipboard of macOS, or a stand-in for tests and snapshots.
@MainActor
public protocol ClipboardAccess: AnyObject {
    /// A number that changes each time an app writes to the clipboard.
    var changeCount: Int { get }
    /// The type identifiers of the content, such as `public.utf8-plain-text`.
    var types: [String] { get }
    /// The plain text of the clipboard, if it holds text.
    func string() -> String?
    /// Puts the text on the clipboard, in the place of its content.
    func write(_ text: String)
}

@MainActor
public final class MemoryPasteboard: ClipboardAccess {
    public static let textType = "public.utf8-plain-text"

    public private(set) var changeCount = 0
    public private(set) var types: [String] = []
    private var text: String?

    public init() {}

    public func string() -> String? { text }

    public func write(_ text: String) {
        copy(text)
    }

    /// A copy in another app, with the types that the app writes.
    public func copy(_ text: String?, types: [String] = [MemoryPasteboard.textType]) {
        self.text = text
        self.types = types
        changeCount += 1
    }
}

/// Adds each new copy of text to the clipboard history.
///
/// macOS has no notification for a change of the clipboard. The app calls
/// `poll()` on a timer. A poll with no change compares one number.
@MainActor
public final class ClipboardWatcher {
    /// The types that password managers put on the clipboard with a secret.
    /// The convention is at nspasteboard.org.
    public static let skippedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
    ]
    /// A copy of a file holds its name as text. The name is not a text that
    /// the user copied.
    private static let fileType = "public.file-url"

    private let pasteboard: any ClipboardAccess
    private let history: ClipboardHistory
    private let shouldSkip: () -> Bool
    private let onChange: () -> Void
    private var lastChange: Int

    /// - Parameters:
    ///   - shouldSkip: True when the history must not keep a copy, such as
    ///     while the focused field is a password field or holds private text.
    ///   - onChange: Called after each change of the clipboard.
    public init(
        pasteboard: any ClipboardAccess,
        history: ClipboardHistory,
        shouldSkip: @escaping () -> Bool = { false },
        onChange: @escaping () -> Void = {}
    ) {
        self.pasteboard = pasteboard
        self.history = history
        self.shouldSkip = shouldSkip
        self.onChange = onChange
        // The text on the clipboard at launch was copied before the keyboard
        // ran, so the history does not take it.
        lastChange = pasteboard.changeCount
    }

    public func poll() {
        let change = pasteboard.changeCount
        guard change != lastChange else { return }
        lastChange = change
        defer { onChange() }

        let types = Set(pasteboard.types)
        guard types.isDisjoint(with: Self.skippedTypes), !types.contains(Self.fileType), !shouldSkip(),
            let text = pasteboard.string()
        else { return }
        history.add(text)
    }
}
