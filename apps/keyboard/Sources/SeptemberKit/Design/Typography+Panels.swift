import SwiftUI

extension Typography {
    /// The keys on a shortcut button, such as "⇧⌘Z".
    public static let shortcutKeys = Font.system(size: 13, weight: .medium)
    /// The text on a text button.
    public static let shortcutText = Font.system(size: 11, weight: .medium)
    /// The name above a button under the pointer.
    public static let shortcutTip = Font.system(size: 13, weight: .semibold)
}
