/**
 * Builds the shared autocomplete dictionary from a word list of spoken English.
 *
 * The engine starts with the sentences in `corpus.ts`, which are too few to
 * cover the language. This word list gives the prefix index its breadth.
 *
 * The source is the OpenSubtitles 2018 frequency list of hermitdave, under the
 * MIT license. Subtitles are the closest free record of speech, and speech is
 * what a September user writes. A word list of web text ranks `sorry` at 2263
 * and `tired` at 5678; this list ranks them at 120 and 727.
 *
 * Run `node scripts/build-dictionary.mjs`. It writes the one dictionary used
 * by both apps.
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

import { tokenize } from "../../../packages/core/autocomplete/tokenizer.ts";

const SOURCE =
  "https://raw.githubusercontent.com/hermitdave/FrequencyWords/master/content/2018/en/en_50k.txt";

/** How many words to keep. Above 5000 the keystroke saving stops going up. */
const SIZE = 5000;

/**
 * Words that the app must never offer on its own.
 *
 * A user of September points with less accuracy than a user of a mouse, and
 * a wrong tap speaks the word aloud. The list holds slurs and strong obscenity
 * only. Mild words such as `damn` and `hell` stay, because they are ordinary
 * speech.
 *
 * This blocks the dictionary, not the user. The user layer still learns every
 * word that the user writes, so nobody loses their own vocabulary.
 */
const BLOCKED = new Set(`
cunt cunts nigga niggas nigger niggers faggot faggots fag fags retard retards
retarded spastic spastics spaz cripple crippled dyke dykes tranny trannies
fuck fucks fucked fucker fuckers fucking fuckin motherfucker motherfuckers
shit shits shitty shithead bullshit cock cocks dick dicks pussy pussies
whore whores slut sluts tits titties prick pricks twat twats wank wanker
`.trim().split(/\s+/));

/** A word of letters, with at most one apostrophe inside it. */
const SHAPE = /^[a-z]+(?:'[a-z]+)?$/;

/** True when the tokenizer reads the word as one word, and reads it unchanged. */
function survivesTokenizer(word) {
  const found = tokenize(word).filter((token) => token.kind === "word");
  return found.length === 1 && found[0].normalized === word;
}

const response = await fetch(SOURCE);
if (!response.ok) throw new Error(`${SOURCE} gave ${response.status}`);
const lines = (await response.text()).trim().split("\n");

const kept = [];
const seen = new Set();
for (const line of lines) {
  const word = line.split(" ")[0];
  if (!SHAPE.test(word)) continue;
  if (word.length === 1 && word !== "a" && word !== "i") continue;
  if (BLOCKED.has(word)) continue;
  if (seen.has(word)) continue;
  if (!survivesTokenizer(word)) continue;
  seen.add(word);
  kept.push(word);
  if (kept.length === SIZE) break;
}

if (kept.length < SIZE) throw new Error(`only ${kept.length} words survived`);

const here = dirname(fileURLToPath(import.meta.url));
const target = join(
  here,
  "..",
  "..",
  "..",
  "packages",
  "core",
  "autocomplete",
  "dictionary.ts",
);

const file = `/**
 * The ${SIZE} most frequent words of spoken English, in order of frequency.
 *
 * Generated by \`scripts/build-dictionary.mjs\`. Do not edit by hand.
 *
 * Source: OpenSubtitles 2018 word counts, from hermitdave/FrequencyWords,
 * under the MIT license. Subtitles record speech, and speech is what a
 * September user writes.
 *
 * The engine puts these words in the prefix index only. A flat word list holds
 * no real pairs of words, so it never goes into the n-gram model.
 *
 * Slurs and strong obscenity are removed. See the script for the reason.
 */
export const DICTIONARY: readonly string[] = \`
${kept.join("\n")}
\`
  .trim()
  .split("\\n");
`;

writeFileSync(target, file, "utf8");
console.log(`${kept.length} words -> ${target}`);
